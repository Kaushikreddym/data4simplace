#!/bin/bash
# =============================================================================
# SIMPLACE-only Europe rerun with the corrected initial mineral N.
#
#   ./submit/submit_simplace_nfix.sh --dry-run      # prepare, print the plan
#   ./submit/submit_simplace_nfix.sh --build-only   # prepare, build, validate
#   ./submit/submit_simplace_nfix.sh                # prepare, build, submit
#   ./submit/submit_simplace_nfix.sh --status | --retry
#
# EU_val's soil_long.csv was written before the stock -> concentration fix in
# data4simplace.exporters.layout._stock_to_concentration (10^4*t dm3 instead of
# 10^5*t), so its NH4_mg_kg / NO3_mg_kg are exactly 10x high. The conversion is
# linear and no other column depends on it, so the corrected file is the old
# one with those two columns divided by 10 -- bit-for-bit what a re-export
# would write, without re-running the tiled SoilGrids stage.
#
# The derived export symlinks every other file of EU_val, so weather, site,
# management and soil.csv are the identical inputs the baseline ran on and the
# only difference between the two runs is the initial mineral N:
#
#   baseline : <output_dir>/winter_wheat_2000_2024_euval/simplace
#   this run : <output_dir>/${NFIX_RUN_NAME}/simplace
# =============================================================================

set -uo pipefail

SUBMIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "${SUBMIT_DIR}")"

SRC_EXPORT="${NFIX_SRC_EXPORT:-/data01/FDS/muduchuru/Data/SIMPLACE/cropmodelling4eu_inputs/exports/mswx/EU_val}"
DST_EXPORT="${NFIX_DST_EXPORT:-/data01/FDS/muduchuru/Data/SIMPLACE/cropmodelling4eu_inputs/exports/mswx/EU_val_nfix}"
NFIX_RUN_NAME="${NFIX_RUN_NAME:-winter_wheat_2000_2024_euval_nfix}"
NFIX_CONFIG="${NFIX_CONFIG:-${SUBMIT_DIR}/config_nfix.yaml}"

case " $* " in
    *" -h "*|*" --help "*) sed -n '2,23p' "${BASH_SOURCE[0]}"; exit 0 ;;
esac

# shellcheck disable=SC1091
source "${SUBMIT_DIR}/simplace_env.sh"
sp_activate

# --- Derived export (idempotent) ---------------------------------------------
python - "${SRC_EXPORT}" "${DST_EXPORT}" <<'EOF' || exit 1
import sys
from pathlib import Path

import pandas as pd

src, dst = map(Path, sys.argv[1:3])
target = dst / "soil" / "soil_long.csv"
if target.is_file():
    print(f"Derived export already present: {dst}")
    sys.exit(0)

(dst / "soil").mkdir(parents=True, exist_ok=True)
for entry in src.iterdir():
    if entry.name != "soil" and not (dst / entry.name).exists():
        (dst / entry.name).symlink_to(entry)
for entry in (src / "soil").iterdir():
    if entry.name != "soil_long.csv" and not (dst / "soil" / entry.name).exists():
        (dst / "soil" / entry.name).symlink_to(entry)

frame = pd.read_csv(src / "soil" / "soil_long.csv", sep=None, engine="python")
columns = [c for c in ("NH4_mg_kg", "NO3_mg_kg", "ammonium", "nitrate") if c in frame]
if not columns:
    sys.exit(f"{src}/soil/soil_long.csv has no mineral-N column to correct")
before = frame[columns].median()
frame[columns] = frame[columns] / 10.0
partial = target.with_suffix(".csv.part")
frame.to_csv(partial, index=False)
partial.rename(target)
for c in columns:
    print(f"  {c}: median {before[c]:.2f} -> {frame[c].median():.2f} mg/kg")
print(f"Derived export written: {dst} ({len(frame)} rows)")
EOF

# --- Derived config: the production config with only export_dir + run_name ---
python - "${SP_CONFIG}" "${NFIX_CONFIG}" "${DST_EXPORT}" "${NFIX_RUN_NAME}" <<'EOF' || exit 1
import sys
from pathlib import Path

import yaml

src, dst, export_dir, run_name = sys.argv[1:5]
config = yaml.safe_load(Path(src).read_text())
config["run_name"] = run_name
config["paths"]["export_dir"] = export_dir
Path(dst).write_text(
    f"# Generated by submit_simplace_nfix.sh from {src}; do not edit.\n"
    + yaml.safe_dump(config, sort_keys=False)
)
print(f"Config: {dst} (run_name={run_name}, export_dir={export_dir})")
EOF

export SP_CONFIG="${NFIX_CONFIG}"
export SP_RUN_NAME="${NFIX_RUN_NAME}"
export SP_RUN_DIR=""
exec "${SUBMIT_DIR}/submit_simplace.sh" "$@"
