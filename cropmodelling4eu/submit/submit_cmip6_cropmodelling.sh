#!/bin/bash
# =============================================================================
# SIMPLACE -> handoff -> torchcrop on every finished CMIP6 weather export.
#
#   ./submit/submit_cmip6_cropmodelling.sh --dry-run       # plan per experiment
#   ./submit/submit_cmip6_cropmodelling.sh --build-only    # build + validate only
#   ./submit/submit_cmip6_cropmodelling.sh                 # submit each chain
#   ./submit/submit_cmip6_cropmodelling.sh --status | --retry
#   CMIP6_EXPERIMENTS="MIROC6_historical" ./submit/submit_cmip6_cropmodelling.sh
#
# The exports come from data4simplace's submit/submit_cmip6.sh; one is finished
# when its scenario.json exists (written by --link-base, which refuses while a
# tile is unfinished). Each experiment is the production config with only:
#
#   run_name           winter_wheat_<first>_<last>_<experiment>
#   paths.export_dir   ${CMIP6_OUT_ROOT}/<experiment>
#   season             ${CMIP6_FIRST_HARVEST}..${CMIP6_LAST_HARVEST}
#   simplace window    ${CMIP6_START}..${CMIP6_END}
#   simplace.co2       annual -- the export's site/co2.csv per year, instead of
#                      the solution's single ClimPerCO2 value (verified: a run
#                      whose table switches 284 -> 800 ppm on 1 Jan responds
#                      within the season)
#
# torchcrop's per-day outputs are off (CMIP6_TC_DAILY=1 restores them): over
# 165 seasons they are ~5 GB per shard against a 16 GB task, and an attribution
# compares seasons, not days.
#
# lines_per_task scales with the window: a cell costs ~72 s over 46 years, so
# ~260 s over 165, and 120 lines is a ~9 h task under the 12 h wall clock.
# =============================================================================

set -uo pipefail

SUBMIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "${SUBMIT_DIR}")"

CMIP6_OUT_ROOT="${CMIP6_OUT_ROOT:-/data01/FDS/muduchuru/Data/SIMPLACE/CMIP6_BC}"
CMIP6_START="${CMIP6_START:-1850-01-01}"
CMIP6_END="${CMIP6_END:-2014-12-31}"
# A winter crop sown in autumn 1850 is the first harvest the weather supports.
CMIP6_FIRST_HARVEST="${CMIP6_FIRST_HARVEST:-1851}"
CMIP6_LAST_HARVEST="${CMIP6_LAST_HARVEST:-2014}"
CMIP6_LINES_PER_TASK="${CMIP6_LINES_PER_TASK:-120}"
BASE_CONFIG="${CMIP6_BASE_CONFIG:-${PROJECT_DIR}/config.yaml}"

case " $* " in
    *" -h "*|*" --help "*) sed -n '2,25p' "${BASH_SOURCE[0]}"; exit 0 ;;
esac

EXPERIMENTS="${CMIP6_EXPERIMENTS:-$(find "${CMIP6_OUT_ROOT}" -mindepth 2 -maxdepth 2 \
    -name scenario.json -printf '%h\n' 2>/dev/null | xargs -rn1 basename | sort)}"
if [ -z "${EXPERIMENTS}" ]; then
    echo "No finished CMIP6 export (no ${CMIP6_OUT_ROOT}/*/scenario.json)." >&2
    echo "Run data4simplace's submit/submit_cmip6.sh first." >&2
    exit 1
fi

# shellcheck disable=SC1091
source "${SUBMIT_DIR}/simplace_env.sh"
sp_activate

STATUS=0
for EXP in ${EXPERIMENTS}; do
    EXPORT="${CMIP6_OUT_ROOT}/${EXP}"
    RUN_NAME="winter_wheat_${CMIP6_FIRST_HARVEST}_${CMIP6_LAST_HARVEST}_${EXP}"
    CONFIG="${EXPORT}/_work/cm4eu_${RUN_NAME}.yaml"
    echo ""
    echo "=== ${EXP}"
    if [ ! -f "${EXPORT}/scenario.json" ]; then
        echo "  SKIP: ${EXPORT}/scenario.json missing -- export not finished" >&2
        STATUS=1
        continue
    fi

    python - "${BASE_CONFIG}" "${CONFIG}" "${EXPORT}" "${RUN_NAME}" \
        "${CMIP6_FIRST_HARVEST}" "${CMIP6_LAST_HARVEST}" "${CMIP6_START}" "${CMIP6_END}" \
        "${CMIP6_LINES_PER_TASK}" <<'EOF' || exit 1
import sys
from pathlib import Path

import yaml

src, dst, export_dir, run_name, first, last, start, end, lines = sys.argv[1:10]
config = yaml.safe_load(Path(src).read_text())
config["run_name"] = run_name
config["paths"]["export_dir"] = export_dir
config["season"].update(start_year=int(first), end_year=int(last))
config["simplace"].update(
    start_date=start, end_date=end, co2="annual", lines_per_task=int(lines)
)
Path(dst).parent.mkdir(parents=True, exist_ok=True)
Path(dst).write_text(
    f"# Generated by submit_cmip6_cropmodelling.sh from {src}; do not edit.\n"
    + yaml.safe_dump(config, sort_keys=False)
)
print(f"  config : {dst}")
EOF

    # A subshell per experiment, so the env files re-derive every TC_*/SP_*
    # path from this experiment's run name instead of inheriting the last one's.
    (
        export SP_CONFIG="${CONFIG}" SP_RUN_NAME="${RUN_NAME}" SP_RUN_DIR=""
        export SP_LINES_PER_TASK="${CMIP6_LINES_PER_TASK}"
        export TC_CONFIG="${CONFIG}" TC_DATA_DIR="${EXPORT}" TC_RUN_NAME="${RUN_NAME}"
        export TC_START_YEAR="${CMIP6_FIRST_HARVEST}" TC_END_YEAR="${CMIP6_LAST_HARVEST}"
        export TC_DAILY="${CMIP6_TC_DAILY:-0}"
        unset TC_OUT_DIR TC_SHARD_DIR TC_WORK_DIR TC_CROP_FILE TC_SOWING_FILE TC_CROP_XML
        "${SUBMIT_DIR}/submit_cropmodelling.sh" "$@"
    ) || STATUS=1
done
exit "${STATUS}"
